/**
 * Брейкпоинты для JS-логики.
 *
 * Зеркало `assets/css/vars.less` — единственное место, где значения задаются
 * в TypeScript. В стилях по-прежнему используются только LESS-переменные
 * (@bp-sm и т.д.), хардкодить пиксели в CSS нельзя. При правке vars.less
 * значения нужно синхронизировать здесь.
 */
export const BP = {
    xs: 480,
    sm: 768,
    md: 1024,
    lg: 1280,
} as const

/** Медиа-запрос «шире брейкпоинта», в тех же границах, что и LESS-миксины. */
export const above = (bp: keyof typeof BP) => `(min-width: ${BP[bp] + 1}px)`
